#!/usr/bin/env node
/**
 * Brief 229 — ports the City Pruning Phase 1 package's NEW CSS into one scoped stylesheet:
 *
 *   src/components/city-pruning/pruning.css
 *
 * Sources (the package's `templates/` folder, passed as the only argument):
 *   - Tier 1 city.css from "Service Areas block (pruning #7)" to the end: the v7 hub sections
 *     (`cc-*` office band, `cb-*` service-areas panel, `sc-*` / `sv-*` featured service + list), the v5
 *     fixes, the Nov 5 shared sections v2 (`fin2-*`, `ndc--lockup`) and the Nov 6 license callout.
 *     Everything ABOVE that marker is the base the live hubs already ship (city-hubs.css), unchanged.
 *   - Tier 3 index.html's two inline <style> blocks (`t2-crumbs`, `t3s`, `t3d-*` carousel).
 *   - Locations css/locations.css (`lc-*`, `sa-*`) and State css/state.css (`st-*`).
 *
 * Every selector is prefixed with `#city-hub-v2.pruned`, the root class only the pilot pages render
 * (v7 hubs, town pages, /locations*), so no other page — the control hubs included — can change.
 * Fonts point at the site's next/font faces, like city-hubs.css. Run:
 *   node scripts/city-pruning/port-css.mjs "<…/Phase1_Pilot_2026-11-18/templates>"
 */
import fs from 'node:fs';
import path from 'node:path';

const T = process.argv[2];
if (!T) throw new Error('usage: port-css.mjs <templates dir>');
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', '..');
const OUT = path.join(ROOT, 'src', 'components', 'city-pruning', 'pruning.css');
const SCOPE = '#city-hub-v2.pruned';

const cityCss = fs.readFileSync(path.join(T, 'Tier 1 - City Hub (Highland Park)', 'css', 'city.css'), 'utf8');
const marker = cityCss.indexOf('/* ===== Service Areas block (pruning #7');
if (marker < 0) throw new Error('marker not found in city.css');
const tier1 = cityCss.slice(marker);

const t3html = fs.readFileSync(path.join(T, 'Tier 3 - Town Page (Wilmette)', 'index.html'), 'utf8');
const t3styles = [...t3html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
const locations = fs.readFileSync(path.join(T, 'Locations - Index Page', 'css', 'locations.css'), 'utf8');
const stateIl = fs.readFileSync(path.join(T, 'State Page - Illinois', 'css', 'state.css'), 'utf8');
const stateOh = fs.readFileSync(path.join(T, 'State Page - Ohio', 'css', 'state.css'), 'utf8');
// The two state sheets differ in ONE value (the hero photo's crop); keyed on the page modifier.
const ilCrop = stateIl.match(/\.st-hero>img\{object-position:[^}]+\}/)[0];
const ohCrop = stateOh.match(/\.st-hero>img\{object-position:[^}]+\}/)[0];
const state = stateIl.replace(ilCrop, `${ilCrop.replace('.st-hero>img', '.st-hero--il>img')}\n${ohCrop.replace('.st-hero>img', '.st-hero--oh>img')}`);

/** Prefix every selector of a flat-or-@media stylesheet. */
function scope(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, (c) => (c.includes('*/', 2) ? c : c)); // keep comments
  let out = '';
  let i = 0;
  const prefixList = (sel) =>
    sel
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => `${SCOPE} ${s}`)
      .join(',');
  function block(depthCss) {
    // returns transformed text for a sequence of rules (top level or inside @media)
    let res = '';
    let j = 0;
    while (j < depthCss.length) {
      // comments
      if (depthCss.startsWith('/*', j)) {
        const e = depthCss.indexOf('*/', j + 2);
        res += depthCss.slice(j, e + 2);
        j = e + 2;
        continue;
      }
      const ch = depthCss[j];
      if (/\s/.test(ch)) { res += ch; j++; continue; }
      const open = depthCss.indexOf('{', j);
      if (open < 0) { res += depthCss.slice(j); break; }
      const head = depthCss.slice(j, open).trim();
      // find matching close
      let d = 0, k = open;
      for (; k < depthCss.length; k++) {
        if (depthCss[k] === '{') d++;
        else if (depthCss[k] === '}') { d--; if (d === 0) break; }
      }
      const body = depthCss.slice(open + 1, k);
      if (head.startsWith('@media') || head.startsWith('@supports')) res += `${head}{${block(body)}}`;
      else if (head.startsWith('@')) res += `${head}{${body}}`;
      else res += `${prefixList(head)}{${body}}`;
      j = k + 1;
    }
    return res;
  }
  out = block(css);
  void i;
  return out;
}

const fonts = (css) =>
  css
    // A mask uses only the colour's alpha; Midnight instead of pure black keeps the brand rule literal.
    .replace(/linear-gradient\(180deg,#000 /g, 'linear-gradient(180deg,#0A1B2E ')
    .replace(/'Industry',\s*'Arial'/g, "var(--font-industry),'Arial'")
    .replace(/'Nunito'/g, "var(--font-nunito),'Nunito'");

const header = `/* =====================================================================
   City Pruning Phase 1 Pilot (Brief 229) — scoped stylesheet. GENERATED by
   scripts/city-pruning/port-css.mjs from the package's templates; do not hand-edit (re-run it).

   Loaded ONLY by the pilot pages (v7 hubs /mokena-il /tinley-park-il /skokie-il, the 7 Tier 3 town
   pages, /locations, /locations/illinois, /locations/ohio) through PruningStyles (next/dynamic, the
   gotcha 25 pattern), and every selector is under ${SCOPE} — the root class only those pages
   render — so no other page, the control hubs included, can change.
   ===================================================================== */
`;
const parts = [
  ['Tier 1 hub v7 + shared sections v2 + license (city.css from "Service Areas block")', tier1],
  ['Tier 3 town page (index.html inline styles)', t3styles],
  ['/locations (locations.css)', locations],
  ['State pages (state.css)', state],
];
let css = header;
for (const [title, src] of parts) css += `\n/* ---------- ${title} ---------- */\n${scope(fonts(src))}\n`;
// Pilot-only additions (not in the package): the office card's address name line and the hub crumb.
css += `
/* ---------- Brief 229 additions (port glue, not package design) ---------- */
/* The live hubs' <PhoneLink> and schedule <button> sit where the package had two <a>s. */
${SCOPE} .cc-card .hero-btns button.btn{cursor:pointer;}
/* The design system's "all: revert" reset defeats the [hidden] attribute (the Brief 220 trap): the
   service-areas "no match" line, filtered towns and finder rows rely on it. */
${SCOPE} [hidden]{display:none!important;}
/* The search box is wired by CityHubRoot; until then the list is simply unfiltered. */
${SCOPE} .cb-search input{font-family:var(--font-nunito),'Nunito',sans-serif;}
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, css);
console.log(`[port-css] wrote ${path.relative(ROOT, OUT)} (${css.length} bytes)`);
